"""
Промпты для агентов пайплайна factcheck-agent v4.
Version: 4.0.0
"""

BASE_SYSTEM_PROMPT = """Ты — интеллектуальный агент системы факт-чекинга.
Твоя задача — помогать проверять факты, анализировать источники и генерировать структурированные отчёты.

Общие правила:
1. Отвечай точно, по делу, без воды.
2. Используй предоставленные инструменты только по назначению.
3. Если информации недостаточно — явно укажи это.
4. Соблюдай формат вывода, указанный в задании.
5. Не выдумывай источники и данные.
"""


def build_system_prompt(addendum: str = "") -> str:
    """
    Строит системный промпт для агента, добавляя специфичные инструкции.

    Args:
        addendum: Дополнительные инструкции для конкретного типа агента
                  (чекер, арбитр, планировщик и т.д.)

    Returns:
        Полный системный промпт.
    """
    if not addendum:
        return BASE_SYSTEM_PROMPT

    return f"{BASE_SYSTEM_PROMPT}\n\n{addendum}".strip()

